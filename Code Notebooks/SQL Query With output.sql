-- Show dishes between 7 and 9 dollars
SELECT Name, Price FROM Dishes
WHERE Price BETWEEN 7 and 9
ORDER BY Price Desc;

-- Count number of reservations each day
SELECT COUNT(ReservationID) as nums, strftime('%d',Date) as day FROM Reservations
GROUP BY day;

-- Average party size
SELECT AVG(PartySize) FROM Reservations;

-- Average party size per day
SELECT AVG(PartySize) as avg_size, strftime('%d',Date) as day FROM Reservations
GROUP BY day;

